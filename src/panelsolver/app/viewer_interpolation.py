"""Display-only cell-to-point interpolation; never modifies result artifacts."""

from __future__ import annotations

import numpy as np
import pyvista as pv


def interpolated_surfaces(
    poly: pv.PolyData, scalar_name: str
) -> tuple[tuple[pv.PolyData, bool], ...]:
    """Average within each component/shield group, retaining sharp edges.

    Coincident vertices are joined with zero tolerance in the display copy.
    Edges over 30 degrees are split before averaging; no coordinates or
    source arrays are changed. Only the selected scalar is interpolated.
    """
    if not isinstance(poly, pv.PolyData) or poly.n_cells != poly.n_faces:
        raise ValueError("Smooth colors requires a polygon surface")
    values = np.asarray(poly.cell_data[scalar_name])
    if (
        scalar_name in {"shielded", "stl_index"}
        or values.dtype.kind not in "iuf"
        or values.shape != (poly.n_cells,)
        or not np.isfinite(values).all()
    ):
        raise ValueError("Smooth colors requires a finite continuous cell scalar")
    groups = []
    for name in ("stl_index", "shielded"):
        array = np.asarray(poly.cell_data.get(name, np.zeros(poly.n_cells)))
        if (
            array.shape != (poly.n_cells,)
            or array.dtype.kind not in "biuf"
            or not np.isfinite(array).all()
        ):
            raise ValueError(f"Invalid {name} boundary data")
        groups.append(array)
    keys, group_ids = np.unique(np.column_stack(groups), axis=0, return_inverse=True)
    # Construct an independent display dataset: discard unrelated point/cell
    # arrays, including imported normals, before the VTK filters see them.
    display = pv.PolyData(poly.points.copy(), poly.faces.copy())
    display.cell_data[scalar_name] = values.astype(np.float64)
    surfaces = []
    for group_id, (_component, shielded) in enumerate(keys):
        part = display.extract_cells(np.flatnonzero(group_ids == group_id))
        part = part.extract_surface(algorithm="dataset_surface")
        part = part.clean(
            tolerance=0.0,
            absolute=True,
            lines_to_points=False,
            polys_to_lines=False,
            strips_to_polys=False,
        )
        part = part.compute_normals(
            cell_normals=False,
            point_normals=True,
            split_vertices=True,
            feature_angle=30.0,
            consistent_normals=False,
            auto_orient_normals=False,
            non_manifold_traversal=False,
        )
        # Normals were needed only to split vertices; keep the existing flat
        # lighting behavior and do not interpolate IDs generated by VTK.
        part.point_data.clear()
        for name in tuple(part.cell_data.keys()):
            if name != scalar_name:
                del part.cell_data[name]
        part = part.cell_data_to_point_data(pass_cell_data=True)
        if not np.isfinite(part.point_data[scalar_name]).all():
            raise ValueError("Interpolated colors are not finite")
        surfaces.append((part, bool(shielded)))
    return tuple(surfaces)
